# PlatformIO pre-build script: bundles ../software/ (index.html + its css/js inlined) into ONE gzipped asset in
# lib/_helper/webAssets.gen.h. The ESP32 serves it from flash in a single response, because its web server
# handles one connection at a time and phones open several, so many small files stall the page.
Import("env")  # noqa: F821
import gzip
import pathlib
import re

proj = pathlib.Path(env["PROJECT_DIR"])  # noqa: F821
web = (proj.parent / "software").resolve()
out = proj / "lib" / "_helper" / "webAssets.gen.h"

index = web / "index.html"
if not index.exists():
    raise SystemExit("embedWeb: %s not found" % index)

def read(rel):
    return (web / rel).read_text(encoding="utf-8")

html = index.read_text(encoding="utf-8")
html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', lambda m: "<style>\n%s\n</style>" % read(m.group(1)), html)
html = re.sub(r'<script src="([^"]+)"></script>', lambda m: "<script>\n%s\n</script>" % read(m.group(1)).replace("</script", "<\\/script"), html)
if re.search(r'(href|src)="(css|js)/', html):
    raise SystemExit("embedWeb: unresolved css/js reference in index.html")

data = gzip.compress(html.encode("utf-8"), 9, mtime=0)  # mtime=0: identical output -> no needless recompile
text = "\n".join([
    "// GENERATED by tools/embedWeb.py from software/ - do not edit.",
    "#pragma once",
    "#include <stddef.h>",
    "#include <stdint.h>",
    "static const uint8_t webIndexGz[] = {%s};" % ",".join(str(b) for b in data),
    "static const size_t webIndexGzLen = %d;" % len(data),
]) + "\n"

if not out.exists() or out.read_text() != text:
    out.write_text(text)
    print("embedWeb: bundled page %d bytes -> %d gzipped" % (len(html.encode("utf-8")), len(data)))
